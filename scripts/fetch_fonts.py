"""Download Google Fonts as WOFF2 for self-hosting."""
import urllib.request
import re
import os

FONTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "assets", "fonts")
os.makedirs(FONTS_DIR, exist_ok=True)

UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120.0.0.0 Safari/537.36"

REQUESTS = [
    # name, url
    ("inter", "https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600&display=swap"),
    ("cormorant", "https://fonts.googleapis.com/css2?family=Cormorant+Garamond:wght@300;400;500;600&display=swap"),
    ("amiri", "https://fonts.googleapis.com/css2?family=Amiri:ital,wght@0,400;0,700;1,400&display=swap"),
]

def fetch_css(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=15) as r:
        return r.read().decode("utf-8")

def download_woff2(woff_url, dest_path):
    req = urllib.request.Request(woff_url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=15) as r:
        data = r.read()
    with open(dest_path, "wb") as f:
        f.write(data)
    return len(data)

results = {}

for font_name, css_url in REQUESTS:
    print(f"\n--- {font_name} ---")
    css = fetch_css(css_url)
    # Find all /* latin */ blocks with woff2 urls
    # Pattern: /* latin */ ... url(URL) format('woff2') ... font-weight: W; font-style: S;
    blocks = re.findall(
        r'/\*\s*(latin[^\*]*?)\*/\s*@font-face\s*\{([^}]+)\}',
        css, re.DOTALL
    )
    if not blocks:
        # Fallback: get all woff2 urls
        blocks_fallback = re.findall(r'@font-face\s*\{([^}]+)\}', css, re.DOTALL)
        blocks = [("", b) for b in blocks_fallback]

    urls_downloaded = []
    for subset, block in blocks:
        woff_match = re.search(r'url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)', block)
        weight_match = re.search(r'font-weight:\s*(\d+)', block)
        style_match = re.search(r'font-style:\s*(\w+)', block)
        if not woff_match:
            continue
        woff_url = woff_match.group(1)
        weight = weight_match.group(1) if weight_match else "400"
        style = style_match.group(1) if style_match else "normal"
        
        fname = f"{font_name}-{weight}"
        if style == "italic":
            fname += "-italic"
        fname += ".woff2"
        dest = os.path.join(FONTS_DIR, fname)
        
        if os.path.exists(dest):
            print(f"  Skip (exists): {fname}")
            urls_downloaded.append((weight, style, fname))
            continue
        
        size = download_woff2(woff_url, dest)
        print(f"  Downloaded: {fname} ({size:,} bytes)")
        urls_downloaded.append((weight, style, fname))
    
    results[font_name] = urls_downloaded

# Generate fonts.css
css_lines = [
    "/* Self-hosted Google Fonts — generated by scripts/fetch_fonts.py */",
    "/* Replaces render-blocking Google Fonts CDN link */",
    "",
]

FAMILY_MAP = {
    "inter": ("Inter", "--nh-font-sans"),
    "cormorant": ("Cormorant Garamond", "--nh-font-serif"),
    "amiri": ("Amiri", "--nh-font-arabic"),
}

for font_name, entries in results.items():
    family, _ = FAMILY_MAP[font_name]
    for weight, style, fname in entries:
        css_lines.append(f"@font-face {{")
        css_lines.append(f"  font-family: '{family}';")
        css_lines.append(f"  font-style: {style};")
        css_lines.append(f"  font-weight: {weight};")
        css_lines.append(f"  font-display: swap;")
        css_lines.append(f"  src: url('/assets/fonts/{fname}') format('woff2');")
        css_lines.append(f"  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;")
        css_lines.append(f"}}")
        css_lines.append("")

fonts_css_path = os.path.join(FONTS_DIR, "..", "css", "fonts.css")
with open(fonts_css_path, "w", encoding="utf-8") as f:
    f.write("\n".join(css_lines))

print(f"\n✅ fonts.css written to {fonts_css_path}")
print("Done!")
